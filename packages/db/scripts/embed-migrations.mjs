import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Embed migration SQL into a TypeScript module.
 *
 * The Worker provisions a new user's database at signup, and a Worker has no
 * filesystem — so the SQL has to travel in the bundle. Generating a plain .ts
 * module keeps this portable across wrangler, vitest and Node, instead of
 * relying on bundler-specific text imports.
 */
const root = join(import.meta.dirname, "..");

const read = (tier) => {
  const dir = join(root, "migrations", tier);
  return readdirSync(dir)
    .filter((name) => name.endsWith(".sql"))
    .sort()
    .map((name) => ({ name, sql: readFileSync(join(dir, name), "utf8") }));
};

const serialise = (entries) =>
  entries
    .map(
      (e) =>
        `  { name: ${JSON.stringify(e.name)}, sql: ${JSON.stringify(e.sql)} },`,
    )
    .join("\n");

const directory = read("directory");
const user = read("user");

mkdirSync(join(root, "src/generated"), { recursive: true });
writeFileSync(
  join(root, "src/generated/migrations.ts"),
  `// Generated by scripts/embed-migrations.mjs — do not edit.
export interface Migration {
  name: string;
  sql: string;
}

export const DIRECTORY_MIGRATIONS: Migration[] = [
${serialise(directory)}
];

export const USER_MIGRATIONS: Migration[] = [
${serialise(user)}
];
`,
);

console.log(
  `embedded ${directory.length} directory and ${user.length} user migration(s)`,
);
